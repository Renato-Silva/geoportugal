export type MessageKey = keyof typeof messages.pt

function initialLang(): Lang {
  const saved = readStore<Lang | null>('geoportugal:lang', null)
  if (saved === 'pt' || saved === 'en') return saved
  return navigator.language?.toLowerCase().startsWith('pt') ? 'pt' : 'en'
}

const lang = ref<Lang>(initialLang())

watch(lang, (l) => {
  writeStore('geoportugal:lang', l)
  document.documentElement.lang = l
}, { immediate: true })

export function useI18n() {
  function t(key: MessageKey, params?: Record<string, string | number>) {
    let s: string = messages[lang.value][key] ?? key
    if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v))
    return s
  }
  const toggleLang = () => { lang.value = lang.value === 'pt' ? 'en' : 'pt' }
  return { t, lang, toggleLang }
}
